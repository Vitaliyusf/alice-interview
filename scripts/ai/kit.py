#!/usr/bin/env python3
# ruff: noqa: E501, RUF100  (long help strings; copied into projects with other line lengths)
"""Everyday commands for the agent kit. Standard library only; works on Windows, macOS and Linux.

    python scripts/ai/kit.py doctor                    what is installed, what is missing, how to fix it
    python scripts/ai/kit.py new AUTH "Rate limit login" [--priority P1] [--depends AUTH-01]
    python scripts/ai/kit.py list [--all]              tasks and their status
    python scripts/ai/kit.py next                      the next task to work on, and the command to run
    python scripts/ai/kit.py start AUTH-03             mark active, create the branch, print the agent command
    python scripts/ai/kit.py status AUTH-03 blocked    change a task's status
    python scripts/ai/kit.py done AUTH-03              mark done, move to tasks/done/, rebuild the index
    python scripts/ai/kit.py index                     rebuild docs/ai/tasks/INDEX.md from the task files
    python scripts/ai/kit.py check [--strict]          run scripts/ai/check_context.py
    python scripts/ai/kit.py install <repo-folder>     copy this kit into another repository

The task files are the source of truth. INDEX.md is generated from them: do not edit it by hand.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AI = ROOT / "docs" / "ai"
TASKS = AI / "tasks"
DONE = TASKS / "done"
TEMPLATE = AI / "TASK_TEMPLATE.md"

STATUSES = ("todo", "active", "blocked", "done")
PRIORITIES = ("P0", "P1", "P2", "P3")
AREA = re.compile(r"^[A-Z][A-Z0-9]{1,15}$")
TASK_ID = re.compile(r"^([A-Z][A-Z0-9]{1,15})-(\d{2,4})$")
INDEX_HEADER = (
    "# Tasks\n\n"
    "<!-- Generated by `python scripts/ai/kit.py index` from the task files. Do not edit by hand. -->\n\n"
)
# Files the installer copies. Paths are relative to the kit root.
KIT_FILES = [
    "AGENTS.md",
    "CLAUDE.md",
    "SETUP.md",
    ".pre-commit-config.yaml",
    ".claude",
    ".github/workflows/agent-context.yml",
    ".github/pull_request_template.md",
    "docs/ai",
    "scripts/ai/check_context.py",
    "scripts/ai/kit.py",
]
GITIGNORE_LINES = [
    ".agent-private/",
    "CLAUDE.local.md",
    ".claude/settings.local.json",
    ".env",
    ".env.*",
    "!.env.example",
    "__pycache__/",
    ".pytest_cache/",
    ".ruff_cache/",
]


class KitError(Exception):
    """A user-facing error: printed without a traceback."""


@dataclass
class Task:
    id: str
    title: str
    status: str
    priority: str
    depends: list[str]
    path: Path

    @property
    def done(self) -> bool:
        return self.status == "done"


# ------------------------------------------------------------------------------------------ task files


def field(text: str, name: str) -> str | None:
    match = re.search(rf"(?m)^{name}:\s*(.+?)\s*$", text)
    return match.group(1) if match else None


def set_field(text: str, name: str, value: str) -> str:
    if re.search(rf"(?m)^{name}:", text):
        return re.sub(rf"(?m)^{name}:.*$", f"{name}: {value}", text, count=1)
    # add it under the Status line, or under the title
    anchor = re.search(r"(?m)^Status:.*$", text) or re.search(r"(?m)^# .*$", text)
    if not anchor:
        return f"{name}: {value}\n" + text
    return text[: anchor.end()] + f"\n{name}: {value}" + text[anchor.end() :]


def parse(path: Path) -> Task:
    text = path.read_text(encoding="utf-8")
    title_match = re.search(r"(?m)^#\s+\S+\s+[—-]+\s+(.+?)\s*$", text)
    depends = field(text, "Depends on") or "none"
    return Task(
        id=path.stem,
        title=title_match.group(1) if title_match else "(no title)",
        status=(field(text, "Status") or "todo").split()[0].lower(),
        priority=(field(text, "Priority") or "P2").split()[0].upper(),
        depends=[] if depends.lower().startswith("none") else re.findall(r"[A-Z][A-Z0-9]*-\d+", depends),
        path=path,
    )


def all_tasks() -> list[Task]:
    tasks = [parse(p) for p in sorted(TASKS.glob("*.md")) if TASK_ID.match(p.stem)]
    tasks += [parse(p) for p in sorted(DONE.glob("*.md")) if TASK_ID.match(p.stem)]
    return tasks


def sort_key(task: Task) -> tuple[str, str, int]:
    area, number = TASK_ID.match(task.id).groups()  # type: ignore[union-attr]
    return (task.priority, area, int(number))


def find(task_id: str) -> Task:
    task_id = task_id.upper()
    for task in all_tasks():
        if task.id == task_id:
            return task
    raise KitError(f"no task {task_id} in docs/ai/tasks/ or docs/ai/tasks/done/")


def write_task(task: Task, text: str) -> None:
    task.path.write_text(text, encoding="utf-8")


def placeholders(path: Path) -> list[str]:
    text = re.sub(r"<!--.*?-->", "", path.read_text(encoding="utf-8"), flags=re.DOTALL)
    return re.findall(r"\{\{[^}]*\}\}", text)


# ------------------------------------------------------------------------------------------ index


def render_index(tasks: list[Task]) -> str:
    active = sorted((t for t in tasks if not t.done), key=sort_key)
    done = sorted((t for t in tasks if t.done), key=lambda t: t.id)
    lines = [INDEX_HEADER.rstrip("\n"), ""]
    lines += [
        "| ID | Title | Status | Priority | Depends on |",
        "|---|---|---|---|---|",
    ]
    for t in active:
        title = t.title.replace("|", "/")
        lines.append(f"| {t.id} | {title} | {t.status} | {t.priority} | {', '.join(t.depends) or 'none'} |")
    lines += ["", "## Done", ""]
    lines += [f"- {t.id} — {t.title}" for t in done] or ["(none yet)"]
    return "\n".join(lines) + "\n"


def write_index() -> Path:
    path = TASKS / "INDEX.md"
    path.write_text(render_index(all_tasks()), encoding="utf-8")
    return path


def index_is_current() -> bool:
    path = TASKS / "INDEX.md"
    return path.exists() and path.read_text(encoding="utf-8") == render_index(all_tasks())


# ------------------------------------------------------------------------------------------ commands


def cmd_new(args: argparse.Namespace) -> None:
    area = args.area.upper()
    if not AREA.match(area):
        raise KitError("the area is 2-16 capital letters or digits, starting with a letter, for example AUTH")
    if args.priority.upper() not in PRIORITIES:
        raise KitError(f"priority must be one of {', '.join(PRIORITIES)}")
    if not TEMPLATE.exists():
        raise KitError(f"{TEMPLATE.relative_to(ROOT)} is missing")
    known = {t.id for t in all_tasks()}
    depends = [d.strip().upper() for d in args.depends.split(",") if d.strip()] if args.depends else []
    unknown = [d for d in depends if d not in known]
    if unknown:
        raise KitError(f"unknown task in --depends: {', '.join(unknown)}")
    numbers = [int(m.group(2)) for t in known if (m := TASK_ID.match(t)) and m.group(1) == area]
    task_id = f"{area}-{(max(numbers) + 1) if numbers else 1:02d}"
    title = " ".join(args.title.split())
    if not title:
        raise KitError("the title is empty")

    text = TEMPLATE.read_text(encoding="utf-8")
    text = re.sub(r"(?m)^# .*$", f"# {task_id} — {title}", text, count=1)
    text = set_field(text, "Status", "todo")
    text = set_field(text, "Priority", args.priority.upper())
    text = set_field(text, "Depends on", ", ".join(depends) or "none")
    if args.goal:
        text = re.sub(
            r"(?ms)^(## Goal\n).*?(?=^## )",
            lambda m: m.group(1) + args.goal.strip() + "\n\n",
            text,
            count=1,
        )
    path = TASKS / f"{task_id}.md"
    path.write_text(text, encoding="utf-8")
    write_index()
    print(f"created {path.relative_to(ROOT).as_posix()}")
    print("next: fill it in, or ask the agent:")
    print(f"  Claude Code: /new-task fill {task_id}")
    print(
        f"  Codex:       Fill in docs/ai/tasks/{task_id}.md from the code. Follow docs/ai/TASK_TEMPLATE.md. Do not implement."
    )


def cmd_list(args: argparse.Namespace) -> None:
    tasks = all_tasks() if args.all else [t for t in all_tasks() if not t.done]
    if not tasks:
        print("no tasks" if args.all else "no open tasks (use --all to see finished ones)")
        return
    done_ids = {t.id for t in all_tasks() if t.done}
    print(f"{'ID':<12} {'STATUS':<8} {'PRI':<4} {'WAITS FOR':<16} TITLE")
    for t in sorted(tasks, key=lambda t: (t.done, *sort_key(t))):
        waits = ", ".join(d for d in t.depends if d not in done_ids) or "-"
        print(f"{t.id:<12} {t.status:<8} {t.priority:<4} {waits:<16} {t.title}")
    if not index_is_current():
        print("\nINDEX.md is out of date: python scripts/ai/kit.py index")


def ready_tasks() -> list[Task]:
    tasks = all_tasks()
    done_ids = {t.id for t in tasks if t.done}
    return sorted(
        (t for t in tasks if t.status == "todo" and all(d in done_ids for d in t.depends)),
        key=sort_key,
    )


def cmd_next(args: argparse.Namespace) -> None:
    active = [t for t in all_tasks() if t.status == "active"]
    for t in active:
        print(f"in progress: {t.id} — {t.title}")
    ready = ready_tasks()
    if not ready:
        print("nothing ready: every todo task waits for another task, or there are no todo tasks")
        return
    t = ready[0]
    print(f"next: {t.id} — {t.title} ({t.priority})")
    print(f"  python scripts/ai/kit.py start {t.id}")


def git(*args: str, check: bool = True) -> str:
    result = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=False)
    if check and result.returncode != 0:
        raise KitError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40].strip("-") or "task"


def cmd_start(args: argparse.Namespace) -> None:
    task = find(args.id)
    if task.done:
        raise KitError(f"{task.id} is already done")
    holes = placeholders(task.path)
    if holes and not args.force:
        raise KitError(
            f"{task.id} still has {len(holes)} placeholder(s), first: {holes[0][:60]}\n"
            f"fill the task first (/new-task fill {task.id}), or pass --force"
        )
    done_ids = {t.id for t in all_tasks() if t.done}
    waiting = [d for d in task.depends if d not in done_ids]
    if waiting and not args.force:
        raise KitError(f"{task.id} waits for {', '.join(waiting)}; pass --force to start anyway")

    branch = None
    if not args.no_branch:
        if git("rev-parse", "--is-inside-work-tree", check=False) != "true":
            raise KitError("not a git repository; pass --no-branch to skip the branch")
        branch = args.branch or f"{args.prefix}/{task.id.lower()}-{slug(task.title)}"
        current = git("branch", "--show-current", check=False)
        if current != branch:
            exists = git("rev-parse", "--verify", "--quiet", f"refs/heads/{branch}", check=False)
            git("switch", branch) if exists else git("switch", "-c", branch)
    write_task(task, set_field(task.path.read_text(encoding="utf-8"), "Status", "active"))
    write_index()
    print(f"{task.id} is active" + (f" on branch {branch}" if branch else ""))
    print("now run one of:")
    print(f'  claude "/task {task.id}"')
    print(
        f'  codex "Implement {task.id}. Follow AGENTS.md. Write a failing test for each acceptance criterion first. Do not commit."'
    )


def cmd_status(args: argparse.Namespace) -> None:
    status = args.status.lower()
    if status not in STATUSES:
        raise KitError(f"status must be one of {', '.join(STATUSES)}")
    if status == "done":
        cmd_done(args)
        return
    task = find(args.id)
    text = set_field(task.path.read_text(encoding="utf-8"), "Status", status)
    if task.done:  # reopening: move it back
        target = TASKS / task.path.name
        task.path.unlink()
        task.path = target
    write_task(task, text)
    write_index()
    print(f"{task.id}: {status}")


def cmd_done(args: argparse.Namespace) -> None:
    task = find(args.id)
    if task.done and task.path.parent == DONE:
        print(f"{task.id} is already done")
        return
    text = set_field(task.path.read_text(encoding="utf-8"), "Status", "done")
    text = set_field(text, "Finished", dt.datetime.now().astimezone().date().isoformat())
    DONE.mkdir(parents=True, exist_ok=True)
    target = DONE / task.path.name
    target.write_text(text, encoding="utf-8")
    if task.path != target:
        task.path.unlink()
    write_index()
    unblocked = [t for t in ready_tasks() if task.id in t.depends]
    print(f"{task.id} done, moved to {target.relative_to(ROOT).as_posix()}")
    for t in unblocked:
        print(f"now ready: {t.id} — {t.title}")


def cmd_index(args: argparse.Namespace) -> None:
    path = write_index()
    print(f"wrote {path.relative_to(ROOT).as_posix()}")


def cmd_check(args: argparse.Namespace) -> int:
    command = [sys.executable, str(ROOT / "scripts" / "ai" / "check_context.py")]
    if args.strict:
        command.append("--strict")
    return subprocess.run(command, cwd=ROOT, check=False).returncode


# ------------------------------------------------------------------------------------------ doctor


def which(name: str) -> str | None:
    for folder in (
        ROOT / "node_modules" / ".bin",
        ROOT / ".venv" / "bin",
        ROOT / ".venv" / "Scripts",
    ):
        found = shutil.which(name, path=str(folder))
        if found:
            return found
    return shutil.which(name)


def cmd_doctor(args: argparse.Namespace) -> int:
    problems = 0

    def line(ok: bool | None, what: str, fix: str = "") -> None:
        nonlocal problems
        mark = {True: "OK  ", False: "FIX ", None: "--  "}[ok]
        if ok is False:
            problems += 1
        print(f"{mark} {what}" + (f"\n       -> {fix}" if fix and ok is not True else ""))

    line(
        sys.version_info >= (3, 10),
        f"Python {sys.version.split()[0]}",
        "Python 3.10 or newer is needed",
    )
    in_git = git("rev-parse", "--is-inside-work-tree", check=False) == "true"
    line(in_git, "git repository", "run: git init")
    if in_git:
        ignored = (
            subprocess.run(["git", "check-ignore", "-q", ".agent-private/"], cwd=ROOT, check=False).returncode
            == 0
        )
        line(
            ignored,
            ".agent-private/ is ignored by git",
            "add .agent-private/ to .gitignore",
        )
        hook = Path(
            git("rev-parse", "--git-path", "hooks/pre-commit", check=False) or ".git/hooks/pre-commit"
        )
        hook = hook if hook.is_absolute() else ROOT / hook
        line(
            hook.exists(),
            "pre-commit hook installed in .git/hooks",
            "run: pre-commit install",
        )
    line(bool(which("pre-commit")), "pre-commit available", "run: pip install pre-commit")
    line(
        bool(which("ruff")) or None,
        "ruff (formats Python after each edit)",
        "optional: pip install ruff",
    )
    line(
        bool(which("prettier")) or None,
        "prettier (formats JS/TS after each edit)",
        "optional: npm i -D prettier",
    )
    line(
        bool(which("claude")) or None,
        "Claude Code CLI on PATH",
        "optional: see the Claude Code docs to install",
    )
    line(bool(which("codex")) or None, "Codex CLI on PATH", "optional")
    if sys.platform == "win32":
        line(
            bool(shutil.which("bash")),
            "Git Bash (runs Claude Code hooks on Windows)",
            "install Git for Windows",
        )

    agents = (ROOT / "AGENTS.md").read_text(encoding="utf-8") if (ROOT / "AGENTS.md").exists() else ""
    holes = len(re.findall(r"\{\{[^}]*\}\}", agents))
    line(
        holes == 0,
        "AGENTS.md filled in",
        f"{holes} placeholders left: run the SETUP-01 task (kit.py start SETUP-01)",
    )
    line(
        index_is_current(),
        "tasks/INDEX.md matches the task files",
        "run: python scripts/ai/kit.py index",
    )
    handoff = ROOT / ".agent-private" / "HANDOFF.md"
    if handoff.exists():
        print(
            f"note  a handoff exists ({handoff.stat().st_size} bytes): continue with "
            "'Continue from .agent-private/HANDOFF.md. Check the diff first.'"
        )
    print("\nall good" if problems == 0 else f"\n{problems} thing(s) to fix")
    return 0 if problems == 0 else 1


# ------------------------------------------------------------------------------------------ install


def cmd_install(args: argparse.Namespace) -> int:
    target = Path(args.target).expanduser().resolve()
    if not target.is_dir():
        raise KitError(f"{target} is not a folder")
    if target == ROOT:
        raise KitError("the target is this repository itself")
    copied, skipped = [], []
    for rel in KIT_FILES:
        src = ROOT / rel
        if not src.exists():
            continue
        files = [p for p in src.rglob("*") if p.is_file()] if src.is_dir() else [src]
        for path in files:
            if "__pycache__" in path.parts or path.name == "settings.local.json":
                continue
            relpath = path.relative_to(ROOT)
            if relpath.parts[:3] == ("docs", "ai", "tasks") and path.name not in (
                "SETUP-01.md",
                ".gitkeep",
            ):
                continue  # this repository's own tasks stay here
            dest = target / relpath
            if dest.exists() and not args.force:
                skipped.append(relpath.as_posix())
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, dest)
            copied.append(relpath.as_posix())
    (target / "docs" / "ai" / "tasks" / "done").mkdir(parents=True, exist_ok=True)

    gitignore = target / ".gitignore"
    existing = gitignore.read_text(encoding="utf-8").splitlines() if gitignore.exists() else []
    missing = [line for line in GITIGNORE_LINES if line not in existing]
    if missing:
        block = (
            ("\n" if existing and existing[-1].strip() else "") + "# agent kit\n" + "\n".join(missing) + "\n"
        )
        with gitignore.open("a", encoding="utf-8") as handle:
            handle.write(block)

    installed_kit = target / "scripts" / "ai" / "kit.py"
    subprocess.run(
        [sys.executable, str(installed_kit), "index"],
        cwd=target,
        check=False,
        capture_output=True,
    )
    print(f"copied {len(copied)} file(s) to {target}")
    if skipped:
        print(f"kept {len(skipped)} existing file(s) (use --force to overwrite):")
        for rel in skipped[:20]:
            print(f"  {rel}")
    if missing:
        print(f".gitignore: added {', '.join(missing)}")
    if shutil.which("pre-commit") and (target / ".git").exists():
        subprocess.run(["pre-commit", "install"], cwd=target, check=False)
    print("\nnext:")
    print(f"  cd {target}")
    print("  python scripts/ai/kit.py doctor")
    print("  python scripts/ai/kit.py start SETUP-01")
    return 0


# ------------------------------------------------------------------------------------------ main


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="kit.py", description="Everyday commands for the agent kit.")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("new", help="create a task file with the next free id")
    p.add_argument("area", help="area prefix, for example AUTH")
    p.add_argument("title", help="short title, in quotes")
    p.add_argument("--priority", default="P2", help="P0 (urgent) .. P3, default P2")
    p.add_argument("--depends", default="", help="comma-separated task ids")
    p.add_argument("--goal", default="", help="one or two sentences for the Goal section")
    p.set_defaults(func=cmd_new)

    p = sub.add_parser("list", help="open tasks")
    p.add_argument("--all", action="store_true", help="include finished tasks")
    p.set_defaults(func=cmd_list)

    sub.add_parser("next", help="the next task to work on").set_defaults(func=cmd_next)

    p = sub.add_parser("start", help="mark a task active and create its branch")
    p.add_argument("id")
    p.add_argument("--branch", help="branch name (default: <prefix>/<id>-<title>)")
    p.add_argument("--prefix", default="feat", help="branch prefix: feat, fix, chore, refactor")
    p.add_argument("--no-branch", action="store_true", help="do not create or switch branches")
    p.add_argument(
        "--force",
        action="store_true",
        help="start even with placeholders or open dependencies",
    )
    p.set_defaults(func=cmd_start)

    p = sub.add_parser("status", help="set a task's status")
    p.add_argument("id")
    p.add_argument("status", help=" | ".join(STATUSES))
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("done", help="finish a task")
    p.add_argument("id")
    p.set_defaults(func=cmd_done)

    sub.add_parser("index", help="rebuild tasks/INDEX.md").set_defaults(func=cmd_index)
    sub.add_parser("doctor", help="check the setup").set_defaults(func=cmd_doctor)

    p = sub.add_parser("check", help="run check_context.py")
    p.add_argument("--strict", action="store_true")
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("install", help="copy this kit into another repository")
    p.add_argument("target", help="the other repository's folder")
    p.add_argument("--force", action="store_true", help="overwrite files that already exist there")
    p.set_defaults(func=cmd_install)
    return parser


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # Windows consoles and the — in titles
    args = build_parser().parse_args(argv)
    try:
        result = args.func(args)
    except KitError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return result if isinstance(result, int) else 0


if __name__ == "__main__":
    sys.exit(main())
